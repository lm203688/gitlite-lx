function generateDiffHtml(commitA, commitB, filePath, repoRoot, isPro) {
  const header = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src vscode-webview-resource: 'unsafe-inline'; script-src 'none'; img-src vscode-webview-resource: data:;">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <link rel="stylesheet" href=" vscode-webview-resource://undefined/style.css">
  <title>Diff Viewer</title>
</head>
<body class="${isPro ? '' : 'free'}">
  <div class="container">
    <div class="header">
      <h1>Diff: ${commitA ? shortHash(commitA) : 'Working Tree'} → ${shortHash(commitB)}</h1>
      <p class="path">${filePath}</p>
    </div>
    <div id="diffContent" class="diff-content"></div>
    <div class="footer">
      <p>Generated by <strong>GitLite</strong>. Your code never leaves your machine.</p>
    </div>
  </div>
</body>
</html>`;
  return header;
}

function shortHash(hash) {
  return hash ? hash.slice(0, 8) : '';
}

function parseDiffLine(line) {
  // Unified diff line classification
  if (line.startsWith('---')) return { type: 'meta', value: line.slice(4).trim() };
  if (line.startsWith('+++')) return { type: 'meta', value: line.slice(4).trim() };
  if (line.startsWith('@@')) return { type: 'hunk', value: line };
  if (line.startsWith('-')) return { type: 'removed', value: line.slice(1) };
  if (line.startsWith('+')) return { type: 'added', value: line.slice(1) };
  return { type: 'context', value: line };
}

function escapeHtml(str) {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

module.exports = { generateDiffHtml, parseDiffLine, escapeHtml };
